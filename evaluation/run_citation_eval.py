import sys
import json
import time
from pathlib import Path

import pandas as pd


# ============================================================
# Paths
# ============================================================

PROJECT_ROOT = Path(__file__).resolve().parent.parent
BACKEND_DIR = PROJECT_ROOT / "backend"

sys.path.insert(0, str(BACKEND_DIR))

from app.retrieval.evidence_pipeline import get_evidence_for_claim
from app.agents.debate_graph import run_debate


DATA_PATH = (
    PROJECT_ROOT
    / "evaluation"
    / "data"
    / "pubhealth_eval_101.csv"
)

DEBATECHECK_RESULTS_PATH = (
    PROJECT_ROOT
    / "evaluation"
    / "results"
    / "debatecheck_results_101_n_runs4.csv"
)

OUTPUT_PATH = (
    PROJECT_ROOT
    / "evaluation"
    / "results"
    / "citation_evaluation_101.csv"
)


RETMAX = 8
MAX_RETRIES = 3
RETRY_WAIT_SECONDS = 65


# ============================================================
# Citation analysis
# ============================================================

def analyse_citations(debate, evidence):
    """
    Evaluate whether citations generated by the debate agents correspond
    to evidence IDs that were actually available to them.

    Invalid IDs are recorded by the debate agents before invalid
    citations are removed from the final DebateTurn.
    """

    evidence_ids = {e.id for e in evidence}

    transcript = debate.get("transcript", [])
    citation_log = debate.get("citation_log", [])

    # Citations that survived validation
    valid_citations = []

    for turn in transcript:
        valid_citations.extend(turn.cited_ids)

    # Invalid / hallucinated citations detected by citation enforcement
    invalid_citations = []
    dropped_points = 0

    for log in citation_log:
        invalid_citations.extend(log.get("invalid_ids", []))
        dropped_points += len(log.get("dropped_points", []))

    total_citation_attempts = (
        len(valid_citations)
        + len(invalid_citations)
    )

    if total_citation_attempts > 0:
        citation_validity = (
            len(valid_citations) / total_citation_attempts
        )
    else:
        citation_validity = None

    unique_valid = set(valid_citations)
    unique_invalid = set(invalid_citations)

    # Defensive check:
    # every surviving citation should exist in retrieved evidence.
    surviving_invalid = [
        cid for cid in valid_citations
        if cid not in evidence_ids
    ]

    return {
        "valid_citations": len(valid_citations),
        "invalid_citations": len(invalid_citations),
        "total_citation_attempts": total_citation_attempts,
        "citation_validity": citation_validity,
        "unique_valid_citations": len(unique_valid),
        "unique_invalid_citations": len(unique_invalid),
        "dropped_points": dropped_points,
        "surviving_invalid_citations": len(surviving_invalid),
        "invalid_ids": json.dumps(
            sorted(unique_invalid),
            ensure_ascii=False
        ),
    }


# ============================================================
# Retrieval with retry
# ============================================================

def retrieve_with_retry(claim):

    last_error = None

    for attempt in range(1, MAX_RETRIES + 1):

        try:
            return get_evidence_for_claim(
                claim,
                retmax=RETMAX,
            )

        except Exception as exc:

            last_error = exc
            error_text = str(exc)

            is_rate_limit = (
                "429" in error_text
                or "RESOURCE_EXHAUSTED" in error_text
            )

            if is_rate_limit and attempt < MAX_RETRIES:

                print(
                    f"  Gemini rate limit -> waiting "
                    f"{RETRY_WAIT_SECONDS}s "
                    f"(attempt {attempt}/{MAX_RETRIES})"
                )

                time.sleep(RETRY_WAIT_SECONDS)
                continue

            raise

    raise last_error


# ============================================================
# Save checkpoint
# ============================================================

def save_results(rows):

    df = pd.DataFrame(rows)

    if not df.empty:
        df = df.drop_duplicates(
            subset=["eval_id"],
            keep="last",
        )

        df = df.sort_values("eval_id")

    df.to_csv(
        OUTPUT_PATH,
        index=False,
    )


# ============================================================
# Main
# ============================================================

def main():

    dataset = pd.read_csv(DATA_PATH)
    previous_results = pd.read_csv(
        DEBATECHECK_RESULTS_PATH
    )

    # Only evaluate claims where the original DebateCheck run
    # successfully retrieved evidence and executed the debate.
    evidence_ids = set(
        previous_results.loc[
            previous_results["evidence_count"] > 0,
            "eval_id"
        ]
    )

    dataset = dataset[
        dataset["eval_id"].isin(evidence_ids)
    ].copy()

    print("=" * 70)
    print("DEBATECHECK CITATION EVALUATION")
    print("=" * 70)
    print(
        f"Claims with retrieved evidence: "
        f"{len(dataset)}/101"
    )
    print()

    # ========================================================
    # Load checkpoint
    # ========================================================

    if OUTPUT_PATH.exists():

        checkpoint = pd.read_csv(OUTPUT_PATH)

        # Only successful rows are preserved.
        # Previous error rows will be retried.
        checkpoint = checkpoint[
            checkpoint["status"] == "completed"
        ].copy()

        rows = checkpoint.to_dict("records")
        completed_ids = set(
            checkpoint["eval_id"]
        )

        print(
            f"Checkpoint loaded: "
            f"{len(completed_ids)} completed claims"
        )
        print()

    else:

        rows = []
        completed_ids = set()

    # ========================================================
    # Evaluation
    # ========================================================

    for _, row in dataset.iterrows():

        eval_id = row["eval_id"]
        claim = row["claim"]

        if eval_id in completed_ids:

            print(
                f"[{eval_id}] Already completed -> skipping"
            )
            continue

        print(
            f"[{eval_id}] Evaluating citations..."
        )

        try:

            # --------------------------------------------
            # Retrieval
            # --------------------------------------------

            retrieval_start = time.time()

            evidence = retrieve_with_retry(
                claim
            )

            retrieval_time = (
                time.time() - retrieval_start
            )

            if not evidence:

                result = {
                    "eval_id": eval_id,
                    "claim": claim,
                    "evidence_count": 0,
                    "valid_citations": 0,
                    "invalid_citations": 0,
                    "total_citation_attempts": 0,
                    "citation_validity": None,
                    "unique_valid_citations": 0,
                    "unique_invalid_citations": 0,
                    "dropped_points": 0,
                    "surviving_invalid_citations": 0,
                    "invalid_ids": "[]",
                    "retrieval_latency": retrieval_time,
                    "status": "no_evidence",
                    "error": "",
                }

            else:

                # ----------------------------------------
                # Debate
                # ----------------------------------------

                debate = run_debate(
                    claim,
                    evidence,
                )

                citation_stats = analyse_citations(
                    debate,
                    evidence,
                )

                result = {
                    "eval_id": eval_id,
                    "claim": claim,
                    "evidence_count": len(evidence),
                    **citation_stats,
                    "retrieval_latency": retrieval_time,
                    "status": "completed",
                    "error": "",
                }

            # Remove any previous row for this claim.
            rows = [
                r for r in rows
                if r["eval_id"] != eval_id
            ]

            rows.append(result)

            # Save immediately after every claim.
            save_results(rows)

            if result["status"] == "completed":

                completed_ids.add(eval_id)

            print(
                f"  evidence={result['evidence_count']} | "
                f"valid={result['valid_citations']} | "
                f"invalid={result['invalid_citations']} | "
                f"dropped={result['dropped_points']}"
            )

        except Exception as exc:

            print(
                f"  ERROR: {exc}"
            )

            error_result = {
                "eval_id": eval_id,
                "claim": claim,
                "evidence_count": None,
                "valid_citations": None,
                "invalid_citations": None,
                "total_citation_attempts": None,
                "citation_validity": None,
                "unique_valid_citations": None,
                "unique_invalid_citations": None,
                "dropped_points": None,
                "surviving_invalid_citations": None,
                "invalid_ids": "",
                "retrieval_latency": None,
                "status": "error",
                "error": str(exc),
            }

            rows = [
                r for r in rows
                if r["eval_id"] != eval_id
            ]

            rows.append(error_result)

            save_results(rows)

    # ========================================================
    # Final summary
    # ========================================================

    results = pd.DataFrame(rows)

    completed = results[
        results["status"] == "completed"
    ]

    errors = results[
        results["status"] == "error"
    ]

    no_evidence = results[
        results["status"] == "no_evidence"
    ]

    total_valid = completed[
        "valid_citations"
    ].sum()

    total_invalid = completed[
        "invalid_citations"
    ].sum()

    total_attempts = (
        total_valid + total_invalid
    )

    if total_attempts > 0:

        overall_validity = (
            total_valid / total_attempts
        )

    else:

        overall_validity = None

    total_dropped = completed[
        "dropped_points"
    ].sum()

    surviving_invalid = completed[
        "surviving_invalid_citations"
    ].sum()

    print()
    print("=" * 70)
    print("CITATION EVALUATION SUMMARY")
    print("=" * 70)

    print(
        f"Target claims:             {len(dataset)}"
    )

    print(
        f"Completed:                 {len(completed)}"
    )

    print(
        f"No evidence on rerun:      {len(no_evidence)}"
    )

    print(
        f"Errors remaining:          {len(errors)}"
    )

    print(
        f"Valid citations:           {int(total_valid)}"
    )

    print(
        f"Invalid citations:         {int(total_invalid)}"
    )

    print(
        f"Total citation attempts:   {int(total_attempts)}"
    )

    if overall_validity is not None:

        print(
            f"Citation validity:         "
            f"{overall_validity:.4f} "
            f"({overall_validity * 100:.2f}%)"
        )

    print(
        f"Dropped points:            {int(total_dropped)}"
    )

    print(
        f"Invalid citations surviving validation: "
        f"{int(surviving_invalid)}"
    )

    print()
    print("Results saved to:")
    print(OUTPUT_PATH)


if __name__ == "__main__":
    main()
